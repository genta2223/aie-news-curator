def parse_converse_response(response: dict[str, Any]) -> CurationResult:
    """Parse Bedrock Converse API response (toolUse or fallback JSON text) into CurationResult."""
    contents = response.get("output", {}).get("message", {}).get("content", [])
    for block in contents:
        if "toolUse" in block:
            tool_input = block["toolUse"].get("input", {})
            return CurationResult.model_validate(tool_input)

    for block in contents:
        if "text" in block:
            raw = block["text"].strip()
            if raw.startswith("```"):
                raw = raw.strip("`")
                if raw.startswith("json"):
                    raw = raw[4:].strip()
            data = json.loads(raw)
            return CurationResult.model_validate(data)

    raise ValueError("Bedrock response did not contain valid toolUse or JSON text output.")


def _mock_curate(
    article: ArticleMetadata,
    lectures: list[dict[str, Any]],
    related_articles: list[RelatedArticleRef] | None = None,
) -> CurationResult:
    """Generate deterministic mock curation output based on enriched lecture metadata."""
    combined = f"{article.title} {article.summary}".lower()
    best_lecture = lectures[0] if lectures else {"title": "Day1: LLM基礎・API・プロンプト設計"}
    best_hits = 0
    matched_kws: list[str] = []

    for lec in lectures:
        hits_list = [kw for kw in lec.get("keywords", []) if kw.lower() in combined]
        if len(hits_list) > best_hits:
            best_hits = len(hits_list)
            best_lecture = lec
            matched_kws = hits_list

    best_title = best_lecture.get("title", "Day1: LLM基礎・API・プロンプト設計")
    score = min(5, 2 + best_hits) if best_hits > 0 else 3
    kw_note = f"（関連キーワード: {', '.join(matched_kws[:3])}）" if matched_kws else ""

    return CurationResult(
        relevance_score=score,
        related_lecture=best_title,
        summary_ja=(
            f"【モック要約】{article.source}から公開された「{article.title[:45]}」に関する記事です。"
            "最新のLLM技術動向と実践的な応用アプローチが紹介されています。"
        ),
        learning_point=(
            f"{best_title}{kw_note} で扱う設計パターンや評価観点を実務・最新研究と結びつけて理解する好例です。"
        ),
        discussion_prompt="この手法を自分の開発タスクや業務システムに組み込むとしたら、どの部分に最も効果がありそうですか？",
        related_articles=related_articles or [],
    )


def _is_rate_limit_error(exc: Exception) -> bool:
    """Return True if an exception indicates a 429 / RESOURCE_EXHAUSTED rate limit."""
    msg = str(exc).lower()
    return "429" in msg or "resource_exhausted" in msg or "rate limit" in msg


def _curate_with_gemini(
    article: ArticleMetadata,
    lecture_list: list[dict[str, Any]],
    model_id: str,
    gemini_client: Any | None = None,
    related_articles: list[RelatedArticleRef] | None = None,
    max_retries: int = 3,
    retry_backoff: float = 2.0,
) -> tuple[CurationResult, int, int]:
    """Call Google Gemini API with structured output and 429 retry handling."""
    client = gemini_client or genai.Client(api_key=os.getenv("GEMINI_API_KEY"))
    prompt = build_curation_prompt(
        article,
        lecture_list,
        related_articles=related_articles,
        use_tool_instruction=False,
    )
    # Do not pass temperature (deprecated on Gemini 3.6+)
    config = types.GenerateContentConfig(
        response_mime_type="application/json",
        response_schema=CurationResult,
    )

    last_exc: Exception | None = None
    response: Any = None
    for attempt in range(max_retries + 1):
        try:
            response = client.models.generate_content(
                model=model_id,
                contents=prompt,
                config=config,
            )
            break
        except Exception as exc:
            last_exc = exc
            if _is_rate_limit_error(exc) and attempt < max_retries:
                wait_sec = retry_backoff * (2**attempt)
                logger.warning("Gemini 429 rate limit hit; retrying in %.1fs...", wait_sec)
                time.sleep(wait_sec)
                continue
            raise
    else:  # pragma: no cover - defensive
        if last_exc:
            raise last_exc

    parsed = getattr(response, "parsed", None)
    if isinstance(parsed, CurationResult):
        curation = parsed
    elif isinstance(parsed, dict):
        curation = CurationResult.model_validate(parsed)
    else:
        curation = CurationResult.model_validate_json(response.text)

    rep_url = article.url.strip()
    curation.related_articles = [
        ref for ref in (related_articles or []) if ref.url.strip() and ref.url.strip() != rep_url
    ]

    usage = getattr(response, "usage_metadata", None)
    in_tokens = int(getattr(usage, "prompt_token_count", 0) or 0)
    out_tokens = int(getattr(usage, "candidates_token_count", 0) or 0)
    return curation, in_tokens, out_tokens


def curate_article(
    article: ArticleMetadata,
    lectures: list[dict[str, Any]] | None = None,
    model_id: str | None = None,
    mock: bool | None = None,
    provider: str | None = None,
    bedrock_client: Any | None = None,
    gemini_client: Any | None = None,
    related_articles: list[RelatedArticleRef] | None = None,
) -> CuratedArticle:
    """Curate a single article via Gemini API, Amazon Bedrock, or mock mode."""
    lecture_list = lectures if lectures is not None else load_lectures_config()
    resolved_provider = resolve_provider(provider=provider, mock=mock)

    start = time.perf_counter()
    if resolved_provider == "mock":
        resolved_model = model_id or os.getenv("GEMINI_MODEL") or os.getenv("BEDROCK_MODEL_ID", DEFAULT_MODEL_ID)
        curation = _mock_curate(article, lecture_list, related_articles=related_articles)
        elapsed_ms = (time.perf_counter() - start) * 1000
        return CuratedArticle(
            article=article,
            curation=curation,
            model_id=f"{resolved_model} (mock)",
            input_tokens=0,
            output_tokens=0,
            latency_ms=round(elapsed_ms, 2),
        )

    if resolved_provider == "gemini":
        resolved_model = model_id or os.getenv("GEMINI_MODEL", DEFAULT_GEMINI_MODEL)
        curation, in_tokens, out_tokens = _curate_with_gemini(
            article=article,
            lecture_list=lecture_list,
            model_id=resolved_model,
            gemini_client=gemini_client,
            related_articles=related_articles,
        )
        elapsed_ms = (time.perf_counter() - start) * 1000
        return CuratedArticle(
            article=article,
            curation=curation,
            model_id=resolved_model,
            input_tokens=in_tokens,
            output_tokens=out_tokens,
            latency_ms=round(elapsed_ms, 2),
        )

    if resolved_provider != "bedrock":
        raise ValueError(f"Unsupported LLM_PROVIDER: {resolved_provider}")

    resolved_model = model_id or os.getenv("BEDROCK_MODEL_ID", DEFAULT_MODEL_ID)
    client = bedrock_client or boto3.client(
        "bedrock-runtime",
        region_name=os.getenv("AWS_REGION") or os.getenv("AWS_DEFAULT_REGION") or DEFAULT_REGION,
    )
    prompt = build_curation_prompt(
        article,
        lecture_list,
        related_articles=related_articles,
        use_tool_instruction=True,
    )
    response = client.converse(
        modelId=resolved_model,
        messages=[{"role": "user", "content": [{"text": prompt}]}],
        toolConfig=_curation_tool_config(),
        inferenceConfig={"maxTokens": 1024, "temperature": 0.2},
    )
    elapsed_ms = (time.perf_counter() - start) * 1000
    curation = parse_converse_response(response)
    rep_url = article.url.strip()
    curation.related_articles = [
        ref for ref in (related_articles or []) if ref.url.strip() and ref.url.strip() != rep_url
    ]
    usage = response.get("usage", {})

    return CuratedArticle(
        article=article,
        curation=curation,
        model_id=resolved_model,
        input_tokens=int(usage.get("inputTokens", 0)),
        output_tokens=int(usage.get("outputTokens", 0)),
        latency_ms=round(elapsed_ms, 2),
    )


def curate_articles(
    articles: list[ArticleMetadata],
    lectures_path: Path | str = DEFAULT_LECTURES_PATH,
    detail_path: Path | str | None = DEFAULT_LECTURES_DETAIL_PATH,
    model_id: str | None = None,
    mock: bool | None = None,
    provider: str | None = None,
    bedrock_client: Any | None = None,
    gemini_client: Any | None = None,
    deduplicate_topics: bool = True,
    similarity_threshold: float = 0.30,
    request_delay: float | None = None,
) -> list[CuratedArticle]:
    """Cluster similar articles (O-4), curate each topic, and sort by relevance_score descending."""
    lectures = load_lectures_config(lectures_path, detail_path=detail_path)
    resolved_provider = resolve_provider(provider=provider, mock=mock)
    delay = (
        request_delay
        if request_delay is not None
        else float(os.getenv("GEMINI_REQUEST_DELAY", "1.5"))
    )

    clusters = (
        cluster_similar_articles(articles, threshold=similarity_threshold)
        if deduplicate_topics
        else [type("Cluster", (), {"representative": a, "related_articles": []})() for a in articles]
    )

    results: list[CuratedArticle] = []
    for idx, cluster in enumerate(clusters):
        if resolved_provider == "gemini" and idx > 0 and delay > 0:
            time.sleep(delay)
        try:
            curated = curate_article(
                article=cluster.representative,
                lectures=lectures,
                model_id=model_id,
                mock=mock,
                provider=provider,
                bedrock_client=bedrock_client,
                gemini_client=gemini_client,
                related_articles=cluster.related_articles,
            )
            results.append(curated)
        except Exception as exc:
            logger.warning("Failed to curate article '%s': %s", cluster.representative.title, exc)

    results.sort(key=lambda item: item.curation.relevance_score, reverse=True)
    return results
