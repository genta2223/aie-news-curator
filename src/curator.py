"""LLM curator module using Amazon Bedrock Converse API (or mock mode)."""

from __future__ import annotations

import json
import logging
import os
import time
from pathlib import Path
from typing import Any

import boto3
import yaml
from dotenv import load_dotenv
from pydantic import BaseModel, Field

from src.collector import ArticleMetadata

load_dotenv()

logger = logging.getLogger(__name__)

DEFAULT_LECTURES_PATH = Path(__file__).resolve().parent.parent / "config" / "lectures.yaml"
DEFAULT_MODEL_ID = "amazon.nova-lite-v1:0"
DEFAULT_REGION = "us-east-1"


class CurationResult(BaseModel):
    """Structured curation output generated by the LLM for an article."""

    relevance_score: int = Field(..., ge=1, le=5, description="講義内容との関連度 (1〜5)")
    related_lecture: str = Field(..., description="最も関連する講義回 (例: Day5: RAG・ハイブリッド検索・Tree/GraphRAG)")
    summary_ja: str = Field(..., description="150文字程度の日本語要約")
    learning_point: str = Field(..., description="受講生にとっての着目ポイント・講義との結びつき解説")
    discussion_prompt: str = Field(..., description="受講生同士の議論を促す短い問いかけ")


class CuratedArticle(BaseModel):
    """Combined article metadata, curation output, and execution metrics."""

    article: ArticleMetadata
    curation: CurationResult
    model_id: str
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: float = 0.0


def load_lectures_config(config_path: Path | str = DEFAULT_LECTURES_PATH) -> list[dict[str, Any]]:
    """Load lecture definitions from YAML."""
    path = Path(config_path)
    with path.open("r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    return data.get("lectures", [])


def format_lectures_context(lectures: list[dict[str, Any]]) -> str:
    """Format lecture definitions into a concise prompt reference block."""
    lines: list[str] = []
    for lec in lectures:
        title = lec.get("title", "")
        desc = lec.get("description", "")
        keywords = ", ".join(lec.get("keywords", []))
        lines.append(f"- {title}: {desc} (キーワード: {keywords})")
    return "\n".join(lines)


def build_curation_prompt(article: ArticleMetadata, lectures: list[dict[str, Any]]) -> str:
    """Build the user prompt instructing Bedrock to evaluate and summarize the article."""
    lectures_text = format_lectures_context(lectures)
    summary_text = article.summary or "(概要なし)"
    return (
        "あなたはAIエンジニア育成講座（AIE）の受講生向けニュースキュレーターです。\n"
        "以下の講義カリキュラムと記事メタデータを読み、受講生の学習に役立つ解説を作成してください。\n\n"
        "## 講義カリキュラム\n"
        f"{lectures_text}\n\n"
        "## 記事メタデータ\n"
        f"- タイトル: {article.title}\n"
        f"- 配信元: {article.source}\n"
        f"- URL: {article.url}\n"
        f"- 概要: {summary_text}\n\n"
        "## 出力要件\n"
        "- relevance_score: 講義内容との関連度を1（低い）〜5（非常に高い）の整数で評価。\n"
        "- related_lecture: 最も関連する講義回をカリキュラムのタイトル形式で指定。\n"
        "- summary_ja: 150文字程度のわかりやすい日本語要約。\n"
        "- learning_point: 受講生にとっての着目ポイントと講義内容との結びつき。\n"
        "- discussion_prompt: 受講生同士がSlackで議論したくなる短い問いかけ。\n"
        "必ずツール `submit_curation` を呼び出して構造化JSONとして回答してください。"
    )


