class CurationResult(BaseModel):
    """Structured curation output generated by the LLM for an article."""

    relevance_score: int = Field(..., ge=1, le=5, description="講義内容との関連度 (1〜5)")
    related_lecture: str = Field(
        ..., description="最も関連する講義回 (例: Day5: RAG・ハイブリッド検索・Tree/GraphRAG)"
    )
    summary_ja: str = Field(..., description="150文字程度の日本語要約")
    learning_point: str = Field(..., description="受講生にとっての着目ポイント・講義との結びつき解説")
    discussion_prompt: str = Field(..., description="受講生同士の議論を促す短い問いかけ")
    related_articles: list[RelatedArticleRef] = Field(
        default_factory=list, description="統合された関連記事（出典・URL）のリスト"
    )


class CuratedArticle(BaseModel):
    """Combined article metadata, curation output, and execution metrics."""

    article: ArticleMetadata
    curation: CurationResult
    model_id: str
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: float = 0.0


def resolve_provider(provider: str | None = None, mock: bool | None = None) -> str:
    """Resolve LLM provider ('mock', 'gemini', or 'bedrock') from args and env vars."""
    if mock is True or os.getenv("USE_MOCK_LLM", "").strip().lower() in {"1", "true", "yes"}:
        return "mock"
    if provider and provider.strip():
        return provider.strip().lower()
    env_provider = os.getenv("LLM_PROVIDER", "").strip().lower()
    if env_provider:
        return env_provider
    if os.getenv("GEMINI_API_KEY", "").strip() and not os.getenv("AWS_ACCESS_KEY_ID", "").strip():
        return "gemini"
    return "bedrock"


def _load_external_lecture_details(detail_path: Path) -> dict[str, dict[str, Any]]:
    """Load optional external lecture detail chunks from JSON if present."""
    if not detail_path.exists():
        return {}
    try:
        with detail_path.open("r", encoding="utf-8") as f:
            raw = json.load(f)
    except Exception as exc:
        logger.warning("Failed to load external lecture details (%s): %s", detail_path, exc)
        return {}

    if isinstance(raw, dict):
        return {str(k): v for k, v in raw.items() if isinstance(v, dict)}
    if isinstance(raw, list):
        return {
            str(item["id"]): item
            for item in raw
            if isinstance(item, dict) and "id" in item
        }
    return {}


def load_lectures_config(
    config_path: Path | str = DEFAULT_LECTURES_PATH,
    detail_path: Path | str | None = DEFAULT_LECTURES_DETAIL_PATH,
) -> list[dict[str, Any]]:
    """Load lecture definitions from YAML and optionally merge external JSON details."""
    path = Path(config_path)
    with path.open("r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    lectures: list[dict[str, Any]] = data.get("lectures", [])

    if detail_path is not None:
        details_map = _load_external_lecture_details(Path(detail_path))
        if details_map:
            for lec in lectures:
                lec_id = str(lec.get("id", ""))
                if lec_id in details_map:
                    extra = details_map[lec_id]
                    for key in ("details", "exercises", "chunks", "notes"):
                        if key in extra:
                            lec[key] = extra[key]
    return lectures


def format_lectures_context(lectures: list[dict[str, Any]]) -> str:
    """Format enriched lecture definitions into a structured prompt reference block."""
    lines: list[str] = []
    for lec in lectures:
        title = lec.get("title", "")
        summary = lec.get("summary") or lec.get("description", "")
        keywords = ", ".join(lec.get("keywords", []))
        use_cases = "; ".join(lec.get("use_cases", []))
        block = [f"### {title}", f"- 要点: {summary}", f"- 技術用語: {keywords}"]
        if use_cases:
            block.append(f"- 応用例: {use_cases}")
        if lec.get("details"):
            block.append(f"- 講義詳細: {lec['details']}")
        if lec.get("exercises"):
            ex = (
                ", ".join(map(str, lec["exercises"]))
                if isinstance(lec["exercises"], list)
                else str(lec["exercises"])
            )
            block.append(f"- 演習テーマ: {ex}")
        lines.append("\n".join(block))
    return "\n\n".join(lines)


def build_curation_prompt(
    article: ArticleMetadata,
    lectures: list[dict[str, Any]],
    related_articles: list[RelatedArticleRef] | None = None,
    use_tool_instruction: bool = True,
) -> str:
    """Build the user prompt instructing the LLM to map article concepts to lecture topics."""
    lectures_text = format_lectures_context(lectures)
    summary_text = article.summary or "(概要なし)"
    related_text = ""
    if related_articles:
        refs = ", ".join(f"{r.source} ({r.title})" for r in related_articles)
        related_text = f"\n- 関連報道（同一トピック統合）: {refs}"

    output_note = (
        "必ずツール `submit_curation` を呼び出して構造化JSONとして回答してください。"
        if use_tool_instruction
        else "指定されたJSONスキーマに従って構造化JSONのみで回答してください。"
    )

    return (
        "あなたはAIエンジニア育成講座（AIE）の受講生向けニュースキュレーターです。\n"
        "以下の講義カリキュラム（要点・技術用語・応用例・演習テーマ）と記事メタデータを照合し、"
        "記事内の技術要素がどの講義回のどの概念・演習に対応するかを具体的に解説してください。\n\n"
        "## 講義カリキュラム\n"
        f"{lectures_text}\n\n"
        "## 記事メタデータ\n"
        f"- タイトル: {article.title}\n"
        f"- 配信元: {article.source}\n"
        f"- URL: {article.url}\n"
        f"- 概要: {summary_text}{related_text}\n\n"
        "## 出力要件\n"
        "- relevance_score: 講義内容との関連度を1（低い）〜5（非常に高い）の整数で評価。\n"
        "- related_lecture: 最も関連する講義回をカリキュラムのタイトル形式で指定。\n"
        "- summary_ja: 150文字程度のわかりやすい日本語要約（記事本文の転載は禁止）。\n"
        "- learning_point: 記事の技術要素が講義のどの概念・キーワード・応用例に対応するかを明示した解説。\n"
        "- discussion_prompt: 受講生同士がSlackで議論したくなる短い問いかけ。\n"
        f"{output_note}"
    )


